#!/usr/bin/env bash
# Regenerate types/ from openapi.yaml. Run after every spec change and commit the result.
#   needs: node (npx) and `pip install datamodel-code-generator`
set -euo pipefail
cd "$(dirname "$0")/.."

npx --yes openapi-typescript@7 openapi.yaml -o types/typescript/analysis-schema.d.ts

names=$(python3 -c "import sys; sys.path.insert(0, 'tools'); import schema; print(' '.join(schema.SPEC['components']['schemas']))")
{
  echo '// Named exports for every schema in openapi.yaml. Generated by tools/gen_types.sh - do not edit.'
  echo 'import type { components } from "./analysis-schema";'
  echo 'type S = components["schemas"];'
  for n in $names; do echo "export type $n = S[\"$n\"];"; done
} > types/typescript/index.ts

datamodel-codegen --input openapi.yaml --input-file-type openapi \
  --output types/python/models.py --output-model-type pydantic_v2.BaseModel \
  --use-annotated --field-constraints --target-python-version 3.10 \
  --disable-timestamp --formatters black isort
echo "types regenerated"
